#!/usr/bin/env python3
"""Generate PACKAGE_REPOS.md (evergreen package -> repo map) and
DISCORD_REPO_HUNT.md (postable repo-hunt comment) for lilalittle/bend-packages.

Usage:
    python3 bin/gen_package_repos.py SNAPSHOT_JSON [DATA_JSON]

- SNAPSHOT_JSON: packages-YYYY-MM-DD.json from the BendHub API
                 ({date, packages: [{hash,name,version,desc,license,...}]})
- DATA_JSON:     data/package_repos.json (curated package -> repo knowledge)

Deterministic. Writes PACKAGE_REPOS.md and DISCORD_REPO_HUNT.md next to the
repo root (two levels up from this script's location, or cwd).
"""
import json, os, re, sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def vkey(v):
    return tuple(int(x) for x in re.findall(r"\d+", v or "0"))

def hub_link(name, hash_):
    if name:
        return f"https://hub.bend-lang.com/n/{name}"
    return f"https://hub.bend-lang.com/{hash_}"

def main():
    snap_path = sys.argv[1]
    data_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "data", "package_repos.json")
    snap = json.load(open(snap_path))
    data = json.load(open(data_path))
    pkgs = data["packages"]
    github_only = data.get("github_only", {})
    snap_date = snap.get("date", str(date.today()))

    # latest version per named package
    latest = {}
    for p in snap["packages"]:
        n = p.get("name")
        if not n:
            continue
        v = p.get("version") or "0"
        if n not in latest or vkey(v) > vkey(latest[n].get("version") or "0"):
            latest[n] = p

    known, unknown = [], []
    for n in sorted(latest):
        info = pkgs.get(n, {"repo": None})
        (known if info.get("repo") else unknown).append((n, latest[n], info))

    # ---- PACKAGE_REPOS.md ----
    out = []
    out.append("# Package → repo map\n")
    out.append(f"> Snapshot: **{snap_date}** · {len(latest)} named packages · "
               f"{len(known)} with a known repo, **{len(unknown)} looking for source**.\n")
    out.append("Every named package on BendHub, A–Z. *Repo* links the source; "
               "*via* says how we know (`hub` = `Source:` link in the hub description, "
               "`curated` = found by searching). "
               "Corrections: edit `data/package_repos.json` and re-run "
               "`bin/gen_package_repos.py` — never hand-edit this file.\n")
    out.append("| Package | Version | Repo | Via |")
    out.append("|---|---|---|---|")
    for n, p, info in known + unknown:
        ver = p.get("version") or "?"
        repo = info.get("repo")
        repo_s = f"[{repo}](https://github.com/{repo})" if repo else "⚠️ unknown"
        via = info.get("via", "") if repo else ""
        note = info.get("note", "")
        if note and not repo:
            repo_s += f" — {note}"
        out.append(f"| [`{n}`]({hub_link(n, p.get('hash',''))}) | `{ver}` | {repo_s} | {via} |")
    if github_only:
        out.append("\n## GitHub-only (not on BendHub)\n")
        out.append("Real repos with Bend code that never published a hub package:\n")
        for n in sorted(github_only):
            g = github_only[n]
            out.append(f"- [{g['repo']}](https://github.com/{g['repo']}) — {g.get('note','')}")
    out.append(f"\n---\n*Generated {snap_date} by `bin/gen_package_repos.py` from the "
               "BendHub snapshot + `data/package_repos.json`.*\n")
    open(os.path.join(ROOT, "PACKAGE_REPOS.md"), "w").write("\n".join(out))

    # ---- DISCORD_REPO_HUNT.md ----
    d = []
    d.append("<!-- Postable Discord comment: help us locate repos for known packages. -->")
    d.append("<!-- Regenerated by bin/gen_package_repos.py — do not hand-edit. -->\n")
    d.append(f"*Repo-hunt list as of {snap_date} — {len(unknown)} packages still looking for source.*\n")
    d.append("---\n")
    d.append("hey all — I'm Tom. I keep a community map of the Bend package ecosystem "
              "(https://github.com/lilalittle/bend-packages) and some of the most "
              "interesting packages on BendHub have **no public repo linked** — which means "
              "we can't audit them, contribute fixes, or fully rely on them.\n")
    d.append("If you authored any of these — or know who did — drop a link? "
              "And if you publish packages, adding a `Source:` link in your hub description "
              "helps the whole ecosystem find your code.\n")
    d.append("**Looking for source:**\n")
    for n, p, info in unknown:
        ver = p.get("version") or "?"
        desc = re.sub(r"\s+", " ", (p.get("desc") or "").strip())
        if len(desc) > 140:
            desc = desc[:137] + "…"
        line = f"- [{n}@{ver}]({hub_link(n, p.get('hash',''))})"
        if desc:
            line += f" — {desc}"
        d.append(line)
    d.append("\nThanks! 🙏 — and if any of these *do* have a repo I missed, that's the best possible reply.")
    open(os.path.join(ROOT, "DISCORD_REPO_HUNT.md"), "w").write("\n".join(d))

    print(f"known={len(known)} unknown={len(unknown)} github_only={len(github_only)}")

if __name__ == "__main__":
    main()
